import_method_val <- function() {
  file_md <- download_file("LC-MS/MS", "Processed Method Val Files", "method validation")
  temp_file <- file_md[[1]]
  mv_name <- file_md[[3]]
  
  on.exit(unlink(temp_file), add = TRUE) # Guaranteed clean-up
  
  sheets <- getSheetNames(temp_file)
  
  #read slopes into dataframe
  slope_df <- if ("Slope and R" %in% sheets) {
    df <- read.xlsx(temp_file, sheet = "Slope and R")
    #handle the NA col names
    colnames(df)[is.na(colnames(df)) | colnames(df) == ""] <- paste0("Col_", seq_along(colnames(df)[is.na(colnames(df)) | colnames(df) == ""]))
    
    first_col_name <- colnames(df)[1]
    df %>% 
      slice(1) %>% 
      column_to_rownames(var = first_col_name)
  } else NULL
  
  #get expected values for QAQC calcs
  expected_native <- NULL
  expected_ISTD <- NULL
  if ("Variations" %in% sheets) { 
    var_df <- read.xlsx(temp_file, sheet = "Variations")
    expected_native <- var_df[1, -1, drop = FALSE]
    expected_ISTD   <- var_df[5, -1, drop = FALSE]
  }
  
  #get LOD, LOB, LOQ
  limits_df <- if ("LOB LOD" %in% sheets) { 
    read.xlsx(temp_file, sheet = "LOB LOD") %>% 
      slice(c(3, 7, 8)) %>% 
      column_to_rownames(var = colnames(.)[1])
  } else NULL
  
  list(
    expected_native = expected_native, 
    expected_ISTD   = expected_ISTD, 
    slope_df        = slope_df, 
    limits_df       = limits_df, 
    mv_name         = mv_name
  )}

format_df <- function(df, mapping) {
  df <- as.data.frame(df) %>%
    rename_with(normalize_analyte_names) %>%
    mutate(across(everything(), as.numeric))
  
  # Match normalized target analytes
  target_analytes <- mapping[["Analyte"]]
  available_cols  <- colnames(df)
  
  # Select columns present in mapping
  valid_cols <- intersect(target_analytes, available_cols)
  
  if (length(valid_cols) == 0) {
    warning("No column names in the data frame match mapping analytes after normalization.")
    return(df)
  }
  
  df[, valid_cols, drop = FALSE]
}

QAQC <- function(cal_data, expected_native, expected_ISTD, slope_df, mapping) {
  analytes <- mapping[["Analyte"]]
  istds    <- mapping[["ISTD"]]
  
  # Helper func to summarize metrics across a set of columns vectorially
  calc_metrics <- function(data, cols, expected_row) {
    sub_data <- data[, cols, drop = FALSE]
    
    avg <- colMeans(sub_data, na.rm = TRUE)
    sdev <- apply(sub_data, 2, sd, na.rm = TRUE)
    rsd  <- (sdev / avg) * 100
    pct_exp <- (avg / as.numeric(expected_row)) * 100
    
    bind_rows(
      Average = avg,
      Std_Dev = sdev,
      RSD = rsd,
      Percent_of_Expected = pct_exp,
      .id = "Metric"
    ) %>% column_to_rownames("Metric")
  }
  
  native_df <- calc_metrics(cal_data, analytes, expected_native)
  ISTD_df   <- calc_metrics(cal_data, istds, expected_ISTD)
  colnames(ISTD_df) <- analytes
  
  # Response Ratio (RR) Summary Metrics
  RR_df <- cal_data[, analytes] / cal_data[, istds]
  
  # Concentration Metrics (ng/ml)
  # Calculate per-run concentration matrix
  aligned_slope <- as.numeric(slope_df[1, analytes])
  conc_raw <- sweep(RR_df, 2, aligned_slope, "/")
  
  avg_conc <- colMeans(conc_raw, na.rm = TRUE)
  conc_metrics <- bind_rows(
    Average            = avg_conc,
    Percent_Difference = (1 - avg_conc) / ((avg_conc + 1) / 2) * 100,
    Accuracy           = avg_conc * 100,
    .id = "Metric"
  )
  
  # Bind run-by-run concentrations with summarized metrics
  conc_df <- bind_rows(
    conc_raw %>% rownames_to_column(var = "Metric"),
    conc_metrics
  ) %>% 
    column_to_rownames(var = "Metric")

  list(native_df = native_df, ISTD_df = ISTD_df, RR_df = RR_df, conc_df = conc_df)
}

peak_areas <- function(all_data, native_df, ISTD_df, slope_df, mapping) {
  analytes <- mapping[["Analyte"]]
  istds    <- mapping[["ISTD"]]
  
  # need corrected RR_df and conc_df
  native_ratio <- as.numeric(native_df["Percent_of_Expected", ]) / 100
  ISTD_ratio   <- as.numeric(ISTD_df["Percent_of_Expected", ]) / 100
  
  #divide each row by the native or ISTD ratio
  corrected_native <- sweep(all_data[, analytes], 2, native_ratio, "/")
  corrected_ISTD   <- sweep(all_data[, istds], 2, ISTD_ratio, "/")
  
  #calculate new concentrations using corrected areas ratio divided by method val slope
  corrected_RR_df <- corrected_native / corrected_ISTD
  corrected_RR_df[is.infinite(as.matrix(corrected_RR_df))] <- NA

  aligned_slope <- as.numeric(slope_df[1, analytes])
  corrected_conc <- sweep(corrected_RR_df, 2, aligned_slope, "/")
  
  list(
    corrected_conc = corrected_conc, 
    corrected_native  = corrected_native, 
    corrected_ISTD    = corrected_ISTD
  )
  }

blank_subs <- function(concentration_df, limit_df) {
  #calc 95(?)% confidence interval for maximal blank concentrations
  ### MUST USE NUMERIC CONC DF WITH NAs, NOT WITH STRING FLAGS
  
  if (!all(colnames(concentration_df) %in% colnames(limit_df)))
  {
    wanring("can't check df against limit: mismatch in column names")
    return (concentration_df)
  }

  #make sure analytes are in same order for limit vector
  limit_vec <- as.numeric(limit_df[1, colnames(concentration_df)])
  
  is_blank <- grep("blank", rownames(concentration_df), ignore.case = TRUE)
  blank_vals <- concentration_df[is_blank, , drop = FALSE]
  
  # Calculate maximal blank vectorially
  maximal_blank <- map2_dbl(blank_vals, limit_vec, ~ {
    if (all(is.na(.x))) 0 else mean(.x, na.rm = TRUE) + (.y * 1.895)
  })
  
  conc_mat <- as.matrix(concentration_df)
  conc_mat[is.na(conc_mat)] <- 0
  
  blank_sub_df <- sweep(conc_mat, 2, maximal_blank, "-")
  blank_sub_df[blank_sub_df < 0] <- 0 #floor at zero, no negatives
  
  list(blank_sub_df = as.data.frame(blank_sub_df), maximal_blank = maximal_blank)
}

ISTD_recovery <- function(corrected_ISTD, expected_ISTD, mapping) {
  percent_recovery <- sweep(corrected_ISTD, 2, unlist(expected_ISTD), '/') * 100
  colnames(percent_recovery) <- mapping[["Analyte"]]
  
  #exclude blank in metrics
  no_blank_pr <- percent_recovery[-grep("blank", rownames(percent_recovery), ignore.case = TRUE), ]

  metrics_df <- data.frame(
    Min     = apply(no_blank_pr, 2, min, na.rm = TRUE),
    Max     = apply(no_blank_pr, 2, max, na.rm = TRUE),
    Median  = apply(no_blank_pr, 2, median, na.rm = TRUE),
    Average = colMeans(no_blank_pr, na.rm = TRUE),
    Std_Dev = apply(no_blank_pr, 2, sd, na.rm = TRUE)
  ) %>% t() %>% as.data.frame()
  
  list(percent_recovery = percent_recovery, metrics_df = metrics_df)
}

check_limit <- function(concentration_df, limit_df, default) {
  if (!all(colnames(concentration_df) %in% colnames(limit_df)))
  {
    warning("can't check df against limit")
    return (concentration_df)
  }
  limit_vec <- as.numeric(limit_df[1, colnames(concentration_df)])

  concentration_df <- round(concentration_df, 3)
  mask <- sweep(as.matrix(concentration_df), 2, limit_vec, "<")
  
  result <- concentration_df
  result[mask] <- default
  result  
}

check_btwn_limits <- function(concentration_df, LOD, LOQ, default) {
  #using LOQ for each analyte, indicate where data is below the threshold
  concentration_df <- round(concentration_df, 3)
  
  result <- map2_dfc(concentration_df, seq_along(concentration_df), function(col, idx) {
    lod_val <- as.numeric(LOD[1, idx])
    loq_val <- as.numeric(LOQ[1, idx])
    
    case_when(
      is.na(col) ~ NA_character_,
      col > lod_val & col < loq_val ~ as.character(default),
      TRUE ~ as.character(col)
    )
  })
  rownames(result) <- rownames(concentration_df)
  result
}

